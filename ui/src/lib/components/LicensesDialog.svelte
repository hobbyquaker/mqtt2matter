<script lang="ts">
    /* The licences behind the § of the top bar: mqtt2matter's own with its NOTICE, then every
       third-party package that ships — the runtime dependencies and what the UI bundle contains. The
       list is generated by the build (licenses.json beside the UI) and loaded when the dialog opens. */
    import {type Licenses, errorMessage} from '../api.ts';
    import {t} from '../i18n.svelte.ts';
    import Dialog from './Dialog.svelte';

    interface Props {
        open: boolean;
        onclose: () => void;
    }

    let {open, onclose}: Props = $props();

    let data = $state<Licenses | undefined>(undefined);
    let error = $state<string | undefined>(undefined);

    $effect(() => {
        if (open && data === undefined) {
            fetch('licenses.json')
                .then(async (response) => {
                    if (!response.ok) {
                        throw new Error(`${response.status} ${response.statusText}`);
                    }
                    data = (await response.json()) as Licenses;
                    error = undefined;
                })
                .catch((e: unknown) => {
                    error = errorMessage(e);
                });
        }
    });

    const groups = $derived(
        data === undefined
            ? []
            : [
                  {id: 'runtime', title: t('Runtime dependencies'), packages: data.runtime},
                  {id: 'ui', title: t('User interface'), packages: data.ui},
              ],
    );
</script>

<Dialog {open} title={t('Licences')} width="720px" {onclose} testId="licenses">
    {#if data}
        <section class="own" data-testid="licenses-self">
            <h3>{data.self.name} {data.self.version} · <span data-testid="licenses-self-license">{data.self.license}</span></h3>
            <details>
                <summary>LICENSE</summary>
                <pre class="ui-pre">{data.self.text}</pre>
            </details>
            <details>
                <summary>NOTICE</summary>
                <pre class="ui-pre">{data.self.notice}</pre>
            </details>
        </section>
        {#each groups as group (group.id)}
            <section data-testid="licenses-{group.id}">
                <h3>{group.title} <span class="ui-faint">({group.packages.length})</span></h3>
                {#each group.packages as pkg (`${pkg.name}@${pkg.version}`)}
                    <details data-testid="license-package">
                        <summary>
                            <span class="name">{pkg.name}</span> <span class="ui-faint">{pkg.version}</span>
                            <span class="ui-badge">{pkg.license}</span>
                        </summary>
                        {#if pkg.repository}
                            <p><a href={pkg.repository} target="_blank" rel="noopener">{pkg.repository}</a></p>
                        {/if}
                        {#if pkg.text}
                            <pre class="ui-pre">{pkg.text}</pre>
                        {:else}
                            <p class="ui-muted">{t('The package has no licence file; its package.json names {license}.', {license: pkg.license})}</p>
                        {/if}
                    </details>
                {/each}
            </section>
        {/each}
    {:else if error}
        <p class="ui-warn-text">{t('The licence list could not be loaded: {error}', {error})}</p>
    {:else}
        <p class="ui-faint">{t('Loading…')}</p>
    {/if}
</Dialog>

