function normalise(name: string): string {
    return name
        .toLowerCase()
        .replace(/ä/g, 'a')
        .replace(/ö/g, 'o')
        .replace(/ü/g, 'u')
        .replace(/ß/g, 'ss')
        .replace(/[^a-z0-9]/g, '');
}

const BY_NORMALISED = new Map<string, string>(Object.keys(TAGS).map((name) => [normalise(name), name]));

/** the Common Area tag for an area name, or undefined when the name matches none */
export function areaTag(name: string): {name: string; id: number} | undefined {
    const key = normalise(name);
    if (key === '') {
        return undefined;
    }
    const tagName = BY_NORMALISED.get(key) ?? SYNONYMS[key];
    if (tagName === undefined) {
        return undefined;
    }
    const id = TAGS[tagName];
    return id === undefined ? undefined : {name: tagName, id};
}

export const AREA_TAGS: Readonly<Record<string, number>> = TAGS;
